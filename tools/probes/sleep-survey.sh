bus=
for d in /sys/bus/i2c/devices/*-0066; do
	[ -e "$d" ] && bus=$(basename "$d" | cut -d- -f1)
done
if [ -n "$bus" ]; then
	for r in 0x00 0x07 0x08 0x0b 0x0c 0x0d 0x0e 0x15 0x17 0x18 0x19; do
		echo "S2MPU05_$r i2c-$bus $(i2cget -f -y $bus 0x66 $r)"
	done
	r=26
	while [ $r -le 90 ]; do
		x=$(printf 0x%02x $r)
		echo "S2MPU05_$x i2c-$bus $(i2cget -f -y $bus 0x66 $x)"
		r=$((r + 1))
	done
else
	echo "S2MPU05 not found"
fi
