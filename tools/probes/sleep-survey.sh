#!/bin/sh
# sleep-survey.sh: read-only snapshot of every register the vendor deep-sleep code touches
# (PMU init/prepare/exit, SYS_PWR table, wake masks, pad retention, central sequencers),
# the GPIO power-down (CON_PDN/PUD_PDN) registers of the non-alive banks, and the S2MPU05
# control registers. Output "NAME ADDR VALUE", one per line. See work/notes/deep-sleep.md.
# Reads only: peek (MMIO) and i2cget -f. The PMIC INT1-3 (clear on read) and PWRONSRC/OFFSRC registers are skipped.
# Usage on the phone: sh sleep-survey.sh > /root/sleep-survey.txt
P=/usr/local/bin/peek
rd() { $P "$1" | cut -d" " -f2; }
disp_on=0
[ $(( $(rd 0x10484024) & 0xf )) -eq 15 ] && disp_on=1
while read -r name addr; do
	case $addr in
	0x148c*) [ $disp_on -eq 1 ] || { echo "$name $addr skipped-dispaud-off"; continue; } ;;
	esac
	echo "$name $addr $(rd $addr)"
